def docx():
    d = Document(); st = d.styles['Normal']; st.font.name = 'Calibri'; st.font.size = Pt(11)
    d.add_heading('Лесная почта — релиз на Пикабу Играх', 0)
    d.add_paragraph('Все тексты и данные для Студии Пикабу Игр (games.pikabu.ru/studio). Картинки — в архиве lesnaya-pochta-pikabu-izobrazheniya.zip.')
    d.add_heading('Что сделать в Студии', 1)
    for s in STEPS: d.add_paragraph(s, style='List Number')
    d.add_heading('Вкладка «Информация»', 1)
    t = d.add_table(rows=0, cols=2); t.style = 'Light Grid Accent 1'
    for k, v in INFO:
        r = t.add_row().cells; r[0].text = k; r[1].text = v
    for title, text, lim in [('Краткое описание', SHORT, 250), ('Полное описание / Об игре', FULL, 1024), ('Как играть', HOW, 1024)]:
        d.add_heading(f'{title} ({len(text)} из {lim} знаков)', 2); d.add_paragraph(text)
    d.add_heading('Картинки', 1)
    t = d.add_table(rows=1, cols=2); t.style = 'Light Grid Accent 1'; t.rows[0].cells[0].text = 'Поле'; t.rows[0].cells[1].text = 'Файл'
    for k, v in [('Иконка 1024×1024 (без текста)', IMAGES[0]), ('Обложка 1920×1080 (с названием)', IMAGES[1])] + [(f'Скриншот {i} (1280×720)', IMAGES[1 + i]) for i in range(1, 6)]:
        r = t.add_row().cells; r[0].text = k; r[1].text = v
    d.add_heading('Внутриигровые товары', 1)
    d.add_paragraph('Идентификатор писать точно: по нему игра выдаёт покупку. Цены — как в игре и на сайте.')
    t = d.add_table(rows=1, cols=5); t.style = 'Light Grid Accent 1'
    for c, h in zip(t.rows[0].cells, ['Идентификатор', 'Название', 'Тип', 'Описание', 'Цена']): c.text = h
    for i, n, ty, ds, p in PRODUCTS:
        r = t.add_row().cells; r[0].text = i; r[1].text = n; r[2].text = TYPE[ty]; r[3].text = ds; r[4].text = p + ' ₽'
    d.add_paragraph('Таблица для импорта — tovary-pikabu.csv.')
    d.add_heading('SEO', 1)
    d.add_paragraph(f'Короткое ({len(SEO_S)} знаков): {SEO_S}'); d.add_paragraph(f'Длинное ({len(SEO_L)} знаков): {SEO_L}'); d.add_paragraph('Ключевые слова: ' + KEYS)
    d.add_heading('Что уже сделано в игре для Пикабу', 1)
    for s in DONE: d.add_paragraph(s, style='List Bullet')
    p = d.add_paragraph(); r = p.add_run('Секретный ключ игры никому не пересылать и не вставлять в чат.'); r.bold = True; r.font.color.rgb = RGBColor(0xC0, 0x30, 0x30)
    d.save(OUT / 'teksty-pikabu.docx')

